#!/usr/bin/env python3
"""Embed the documentation resource and generate the Solidity template from XML."""
import argparse
import base64
import json
from pathlib import Path
import re
import subprocess
import xml.etree.ElementTree as ET

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="check generated files without writing")
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
xml_path = root / "resources/fx-spot-trade-template.xml"
stylesheet = (root / "resources/fx-spot-trade-documentation.xslt").read_bytes()
ET.fromstring(stylesheet)
digest = subprocess.run(
    ["cast", "keccak", "0x" + stylesheet.hex()], check=True, capture_output=True, text=True
).stdout.strip()
if not re.fullmatch(r"0x[0-9a-fA-F]{64}", digest):
    raise SystemExit("Unexpected cast keccak output")
uri = "data:application/xslt+xml;base64," + base64.b64encode(stylesheet).decode("ascii")
source = xml_path.read_text()
reference = re.compile(r"<ProductDocumentationTemplate\b[^>]+/>")

def embed(match):
    result = re.sub(r'href="[^"]*"', lambda _: f'href="{uri}"', match.group())
    return re.sub(r'integrity="[^"]*"', lambda _: f'integrity="keccak256-{digest}"', result)

xml, count = reference.subn(embed, source)
if count != 1:
    raise SystemExit("Expected exactly one documentation reference")
ET.fromstring(xml)
literals = ",\n".join("            " + json.dumps(line) for line in xml.splitlines(keepends=True))
solidity = '''// SPDX-License-Identifier: CC0-1.0
pragma solidity ^0.8.24;

// Generated by scripts/generate-xml-template.py from resources/fx-spot-trade-template.xml.
library FxSpotTradeXml {
    function template() internal pure returns (string memory) {
        return string.concat(
''' + literals + '''
        );
    }
}
'''
outputs = {xml_path: xml, root / "contracts/FxSpotTradeXml.sol": solidity}
for path, content in outputs.items():
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f"Regenerate {path.relative_to(root)} with {Path(__file__).name}")
    else:
        path.write_text(content)
print("XML template and Solidity source are consistent." if args.check else "Generated XML template and Solidity source.")
